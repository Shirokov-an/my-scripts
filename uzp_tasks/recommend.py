def _fmt(tpl: str, value: float, tt: dict) -> str:
    return tpl.format(
        value=value,
        norm=config.NORM["cycle_days"],
        p90=tt.get("p90_cycle", 0.0),
        burst_min=config.BURST_MIN_TASKS,
        burst_share=config.BURST_MIN_SHARE,
        conv_len=config.CONVEYOR_MIN_LEN,
        conv_gap=config.CONVEYOR_GAP_MIN,
        low_fill=config.LOW_VALUE_FILL_RATE,
        stub_len=config.STUB_COMMENT_LEN,
        clone_min=config.CLONE_MIN_REPEAT,
    )


def system_recommendations(tt: dict, unit_name: str = "Все ТБ",
                           scope: str = "Система") -> list[dict]:
    """Рекомендации по сработавшим порогам для переданного среза.

    Та же функция обслуживает и канал целиком, и отдельный ТБ: пороги те же,
    меняются только числа на входе. Иначе пришлось бы держать два набора
    формулировок и следить, чтобы они не разошлись.
    """
    tt = dict(tt)
    tt["client_full_share_calc"] = (tt["clients_full"] / tt["clients"]
                                    if tt.get("clients") else 0.0)
    out = []
    for rule in SYSTEM_RULES:
        value = float(tt.get(rule["metric"], 0.0) or 0.0)
        fired = value < rule["threshold"] if rule.get("reverse") else value >= rule["threshold"]
        if not fired:
            continue
        out.append({
            "scope": scope,
            "unit": unit_name,
            "key": rule["key"],
            "priority": rule["priority"],
            "title": rule["title"],
            "finding": _fmt(rule["finding"], value, tt),
            "action": rule["action"],
            "owner": rule["owner"],
            "control": rule["control"],
            "value": round(value, 4),
        })
    return sorted(out, key=lambda r: (r["priority"], -r["value"]))


