TB_GAP = 1.5          # во сколько раз показатель должен превышать медиану
TB_MIN_ABS = 0.10     # и быть не ниже этого значения в абсолюте


def tb_recommendations(tb: pd.DataFrame, emp: pd.DataFrame) -> list[dict]:
    """По каждому ТБ — до трёх адресных пунктов с самым большим отклонением."""
    if tb.empty:
        return []
    out = []
    for metric, title, finding_tpl, action in TB_RULES:
        if metric not in tb:
            continue
        median = float(tb[metric].median())
        for row in tb.itertuples():
            value = float(getattr(row, metric, 0.0) or 0.0)
            if value < TB_MIN_ABS or median <= 0 or value < median * TB_GAP:
                continue
            flagged = ""
            if len(emp):
                sub = emp[(emp["tb_id"] == row.tb_id) & (emp["flags_qty"] > 0)]
                if len(sub):
                    names = ", ".join(sub.nlargest(3, "risk_index")["emp_fio"].tolist())
                    flagged = (f" Под триггерами {len(sub)} сотр., "
                               f"начать с: {names}.")
            out.append({
                "scope": "ТБ",
                "unit": row.tb_name,
                "tb_id": int(row.tb_id),
                "key": metric,
                "priority": 1 if value >= median * 2 else 2,
                "title": title,
                "finding": finding_tpl.format(value=value, median=median) + "." + flagged,
                "action": action,
                "owner": "Руководитель ТБ по каналу УЗП",
                "control": f"{metric}: цель — не выше медианы по системе ({median:.1%}).",
                "value": round(value, 4),
            })
    out.sort(key=lambda r: (r["unit"], r["priority"], -r["value"]))

    # не больше трёх пунктов на ТБ: длинный список никто не выполняет
    capped, seen = [], {}
    for r in out:
        seen[r["unit"]] = seen.get(r["unit"], 0) + 1
        if seen[r["unit"]] <= 3:
            capped.append(r)
    return capped


def describe_flags(emp: pd.DataFrame) -> pd.DataFrame:
    """Расшифровать коды триггеров в человекочитаемое «что проверить».

    Колонка добавляется ВСЕМ сотрудникам, а не только попавшим в красный
    список: тот же датафрейм уходит и в CSV, и в разрезы по ТБ, где отбор
    делается заново.
    """
    if emp.empty:
        return emp
    titles = {k: v["title"] for k, v in config.TRIGGERS.items()}
    emp = emp.copy()
    emp["what_to_check"] = [
        "; ".join(titles[k] for k in str(f).split(",") if k in titles)
        for f in emp["flags"]]
    return emp
