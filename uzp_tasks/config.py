def _load_dotenv(path: Path | None = None) -> None:
    """Прочитать .env в окружение, не затирая уже заданные переменные.

    Свой разбор вместо python-dotenv: пакета нет в requirements, а тянуть
    зависимость ради десяти строк на закрытом контуре — лишний риск установки.
    """
    path = path or (ROOT / ".env")
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        os.environ.setdefault(key.strip(), value.strip())


def db_url(conn: str | None = None) -> str:
    """Строка подключения: аргумент тетрадки → UZP_DB_URL из .env."""
    if conn:
        return conn
    _load_dotenv()
    url = os.environ.get("UZP_DB_URL")
    if not url:
        raise RuntimeError(
            "Не задана строка подключения: передайте conn=... в тетрадке "
            "или положите UZP_DB_URL в .env"
        )
    return url
